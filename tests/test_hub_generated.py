"""A generated page in the hub (SPEC 7.2, 8.5, 10.1): its meta says `edit: false` with a `why`, and `/_/save`, `/_/tick`
and `/_/share` refuse it with 403; comments, replies and resolve work as on any page."""

from helpers import PLAN, page_meta
from sheafmd import diagnostics
from sheafmd import comments as rdc
from sheafmd.source import md_hash

DOC = "work/plan.md"
URL = "/work/plan.md"
WHY = "Generated by builder. Edits are not kept; comment instead."


def mark(hub, by="builder"):
    hub.docs.put(DOC, {**hub.docs.get(DOC), "generated": {"by": by, "id": "tok1", "at": "2026-11-20T10:00:00+0100"}})


def rows(kind):
    return [r for r in diagnostics.read() if r["kind"] == kind]


def test_a_generated_page_has_edit_false_and_the_why_in_its_meta(browser, plan):
    browser.get(URL)
    mark(browser.hub)
    meta = page_meta(browser.get(URL).text)
    assert meta["edit"] is False and meta["why"] == WHY


def test_a_page_that_is_not_generated_keeps_edit_true_and_no_why(browser, plan):
    meta = page_meta(browser.get(URL).text)
    assert meta["edit"] is True and meta["why"] == ""


def test_save_is_refused_and_the_file_is_untouched(browser, plan):
    browser.get(URL)
    mark(browser.hub)
    before = plan.read_text(encoding="utf-8")
    r = browser.post("/_/save", {"doc": DOC, "hash": md_hash(before),
                                 "edits": [{"i": 2, "html": "<p>First paragraph, about plums.</p>"}]})
    assert r.status == 403 and WHY in r.text
    assert plan.read_text(encoding="utf-8") == before
    row = rows("generated-refused")[-1]
    assert row["doc"] == DOC and row["endpoint"] == "/_/save" and "plums" not in str(row)


def test_tick_is_refused(browser, plan):
    browser.get(URL)
    mark(browser.hub)
    r = browser.post("/_/tick", {"doc": DOC, "action": 0, "word": "Approve", "hash": md_hash(PLAN)})
    assert r.status == 403 and WHY in r.text
    assert rows("generated-refused")[-1]["endpoint"] == "/_/tick"


def test_share_is_refused_and_writes_no_share_line(browser, plan):
    browser.get(URL)
    mark(browser.hub)
    before = plan.read_text(encoding="utf-8")
    r = browser.post("/_/share", {"doc": DOC, "hash": md_hash(before)})
    assert r.status == 403 and WHY in r.text
    assert plan.read_text(encoding="utf-8") == before
    assert rows("generated-refused")[-1]["endpoint"] == "/_/share"


def test_comment_reply_and_resolve_still_work(browser, plan):
    browser.get(URL)
    mark(browser.hub)
    text = plan.read_text(encoding="utf-8")
    blk, s, e = rdc.find_quote(text, "Second paragraph")
    r = browser.post("/_/comment", {"doc": DOC, "op": "add", "hash": md_hash(text), "block": blk, "start": s,
                                    "end": e, "quote": "Second paragraph", "body": "Why pears?"})
    assert r.status == 200
    h = lambda: md_hash(plan.read_text(encoding="utf-8"))          # noqa: E731
    r = browser.post("/_/comment", {"doc": DOC, "op": "reply", "hash": h(), "id": "c1", "body": "Because."})
    assert r.status == 200
    r = browser.post("/_/comment", {"doc": DOC, "op": "status", "hash": h(), "id": "c1", "status": "resolved"})
    assert r.status == 200 and rdc.parse(plan.read_text(encoding="utf-8")).by_id("c1").status == "resolved"


def test_a_generated_page_draws_no_action_button_and_says_it_is_generated(browser, plan):
    browser.get(URL)
    mark(browser.hub)
    meta = page_meta(browser.get(URL).text)
    assert meta["actions"] == [] and meta["generated"] is True
