"""A generated page in the browser (SPEC 8.3, 10.1, ticket 156): it says why its text takes no edit, draws no Edit,
and the E key does nothing."""
import pytest
from pagehelp import DOC

pytestmark = pytest.mark.page

WHY = "Generated by builder. Edits are not kept; comment instead."


def test_a_generated_page_shows_its_notice_and_has_no_edit(tab):
    hub = tab.site.hub
    tab.open()                                                  # its entry exists once the page is rendered
    hub.docs.put(DOC, {**hub.docs.get(DOC), "generated": {"by": "builder", "id": "tok1", "at": "2026-11-22T10:00:00+0100"}})
    tab.open()
    assert tab.page.locator("main p.rd-readonly[role=note]").inner_text() == WHY
    assert tab.page.locator("#rd-edit").count() == 0
    tab.page.keyboard.press("e")
    assert "rd-editing" not in (tab.page.locator("body").get_attribute("class") or "")


def test_a_page_that_is_not_generated_shows_no_notice(tab):
    tab.open()
    assert tab.page.locator("main p.rd-readonly").count() == 0
